import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { buildUpdatePackage } from "./build-update-package.mjs";
import { stageWindowsApp } from "./build-windows-app.mjs";
import { decodePackageBundle } from "../work/monitor/lib/self-update/package-bundle.mjs";
import { confirmPackageUpdate } from "../work/monitor/lib/self-update/package-recovery.mjs";
import { createPackageUpdater } from "../work/monitor/lib/self-update/package-update.mjs";

test("真实运行文件：生成小更新包 → 隔离启动新服务 → 应用；不需要替换 exe", async (t) => {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "cwb-real-package-"));
  t.after(() => fs.rmSync(tmp, { recursive: true, force: true, maxRetries: 3 }));
  const electronDist = path.join(tmp, "electron");
  fs.mkdirSync(electronDist);
  fs.writeFileSync(path.join(electronDist, "electron.exe"), "untouched executable");
  const { appDir, resourcesApp } = await stageWindowsApp({ rootDir: path.resolve(import.meta.dirname, ".."), electronDist, outDir: path.join(tmp, "out"), buildInfo: { version: "2.95.0", platform: "win32-x64" } });
  const next = path.join(tmp, "next");
  fs.cpSync(resourcesApp, next, { recursive: true });
  const pkg = JSON.parse(fs.readFileSync(path.join(next, "package.json")));
  pkg.version = "99.0.0";
  fs.writeFileSync(path.join(next, "package.json"), JSON.stringify(pkg));
  const info = JSON.parse(fs.readFileSync(path.join(next, "build-info.json")));
  info.version = pkg.version;
  fs.writeFileSync(path.join(next, "build-info.json"), JSON.stringify(info));
  const name = buildUpdatePackage({ resourcesApp: next, outDir: tmp, arch: "x64" });
  const bytes = fs.readFileSync(path.join(tmp, name));
  assert.equal(decodePackageBundle(bytes).version, "99.0.0");
  assert.ok(bytes.length < 10_000_000);
  const updater = createPackageUpdater({ rootDir: resourcesApp, runtimeDir: path.join(tmp, "data/runtime"), repo: "a/b", platform: "win32", arch: "x64", electronVersion: pkg.devDependencies.electron, fetchBytes: async () => bytes, upgrading: () => false });
  updater.start({ version: pkg.version, update: { url: `https://github.com/a/b/releases/download/v${pkg.version}/${name}`, sha256: createHash("sha256").update(bytes).digest("hex"), size: bytes.length } });
  await updater.wait();
  assert.equal(updater.status().ready, true, JSON.stringify(updater.status()));
  assert.equal(JSON.parse(fs.readFileSync(path.join(resourcesApp, "package.json"))).version, "99.0.0");
  assert.equal(fs.readFileSync(path.join(appDir, "Codex Operations Console.exe"), "utf8"), "untouched executable");
  confirmPackageUpdate(resourcesApp);
});
